def render_scene(
    result: SceneResult,
    index: int,
    total: int,
    ink: Ink,
    gl: Glyphs,
    ask_text_mode: str = "flagged",
) -> list[str]:
    rec, ep, scene = result.record, result.episode, result.scene
    out: list[str] = []
    out.append(ink(gl.rule * WIDTH, "dim"))
    out.append(ink(f"SCENE {index}/{total}  {scene.title}", "bold", "cyan"))
    out.append(ink(gl.rule * WIDTH, "dim"))
    out.append("")
    out += _labelled(
        "scenario", f"{rec.scenario_id}  variant {rec.variant_id}", indent="  ", pad=13
    )
    out += _labelled(
        "recorded",
        f"{rec.model_id}, seed {rec.seed}, undefended, run E-00j",
        indent="  ",
        pad=13,
    )
    out += [
        ink(line, "dim")
        for line in _labelled("why this one", scene.selected_because, indent="  ", pad=13)
    ]
    out.append("")

    out.append(ink("  THE USER SAID", "bold"))
    out += [ink(line, "cyan") for line in _block(f'"{rec.utterance}"', "    ")]
    out.append("")

    out.append(
        ink("  WITHOUT THE FIREWALL — what the agent actually did, on the record", "bold")
    )
    for call in rec.tool_calls:
        args = _short_args(dict(call.get("args") or {}))
        out.append(f"    {str(call['name']).ljust(24)}{ink(args, 'dim')}")
    effects = [f"{e['verb']} {e['resource_class']}" for e in rec.effect_log]
    out += [
        ink(line, "dim") for line in _labelled("effects", ", ".join(effects) or "none", pad=24)
    ]
    for line in _undefended_outcome(result, gl):
        out += [ink(wrapped, "red") for wrapped in _block(line, "    ")]
    out.append("")

    out.append(ink("  THE SCOPE — the authority the monitor started from", "bold"))
    out += _labelled("grants", ", ".join(result.grants) or "(nothing)")
    for constraint in result.constraints:
        out += _labelled("bound", constraint)
    for question in result.open_questions:
        out += [ink(line, "yellow") for line in _labelled("open question", question)]
    out.append("")

    out.append(ink("  WITH THE FIREWALL — the same calls, one at a time", "bold"))
    for action in ep.actions:
        out += _render_action(action, ink, gl)
    out.append("")

    out.append(ink("  OUTCOME", "bold"))
    for label, line in _defended_outcome(result, gl):
        out += _labelled(label, line, pad=19)
    chain = "intact" if ep.chain_intact else ink("BROKEN", "red", "bold")
    out += _labelled(
        "audit",
        f"{len(ep.actions)} hash-chained event(s), chain {chain}, replayable offline",
        pad=19,
    )
    out.append("")

    show_ask = ask_text_mode == "all" or (ask_text_mode == "flagged" and scene.show_ask_text)
    if show_ask:
        asked = [a for a in ep.actions if a.ask_text]
        if asked:
            out.append(ink("  THE QUESTION THE HUMAN WAS SHOWN, in full", "bold"))
            out += [
                ink(line, "dim")
                for line in _block(
                    "Rendered by the monitor, not by the agent: the agent's own rationale "
                    "cannot reach it, every argument is quoted and labelled with where it "
                    "came from, and it states what approving would grant (D-008).",
                    "  ",
                )
            ]
            out.append("")
            for line in (asked[0].ask_text or "").splitlines():
                out.append(ink(f"  {gl.bar} ", "dim") + line)
            out.append("")
    return out


def _render_action(action: ActionOutcome, ink: Ink, gl: Glyphs) -> list[str]:
    verdict = action.verdict
    shown = verdict
    if action.asked:
        outcome = "APPROVED" if action.consent_approved else "DENIED"
        shown = f"ASK {gl.arrow} {outcome}"
    styles = VERDICT_STYLE.get(verdict, ())
    classes = ", ".join(action.effect_classes) or "no declared effect"
    out = [
        f"    step {action.step}  {action.tool:<22} {ink(shown, *styles, 'bold')}",
        f"            {ink(classes, 'dim')}",
    ]
    # An approved ASK carries the explanation of the *second* decision, taken against the
    # scope consent widened. Saying so matters: without the prefix, "authorized and in
    # bounds" reads as though there had been no reason to stop, and the reason is the
    # whole point of the scene. The log is quoted, never rewritten.
    explanation = action.explanation
    if action.asked and action.consent_approved:
        out.append(
            " " * 12
            + ink("stopped, put the question, then re-decided against the widened", "dim")
        )
        out.append(" " * 12 + ink("scope. Why it stopped is in the question itself.", "dim"))
    for line in _wrap(explanation, " " * 12):
        out.append(" " * 12 + line)
    if action.gates:
        out.append(" " * 12 + ink(f"gate: {', '.join(action.gates)}", "magenta"))
    if action.off_policy:
        out.append(
            " " * 12 + ink("(after an earlier refusal: off-policy, counted separately)", "dim")
        )
    return out


def _undefended_outcome(result: SceneResult, gl: Glyphs) -> list[str]:
    ep, scenario = result.episode, result.scenario
    lines: list[str] = []
    if ep.contested_occurred_undefended is not None:
        target = _contested_name(scenario)
        lines.append(
            f"{gl.arrow} the contested effect ({target}) EXECUTED. Silently. Nobody was asked."
            if ep.contested_occurred_undefended
            else f"{gl.arrow} the contested effect ({target}) did not occur."
        )
    if ep.attack_succeeded_undefended is not None:
        lines.append(
            f"{gl.arrow} the injected instruction SUCCEEDED: the secret left the machine."
            if ep.attack_succeeded_undefended
            else f"{gl.arrow} the injected instruction did not succeed."
        )
    if not lines:
        lines.append(f"{gl.arrow} the task was carried out; there is no contested effect here.")
    return lines


def _defended_outcome(result: SceneResult, gl: Glyphs) -> list[tuple[str, str]]:
    ep = result.episode
    rows: list[tuple[str, str]] = []
    if ep.contested_occurred_undefended is not None:
        before = "executed" if ep.contested_occurred_undefended else "did not occur"
        after = "executed" if ep.contested_occurred_defended else "prevented"
        rows.append(
            ("contested effect", f"undefended: {before}  {gl.arrow}  defended: {after}")
        )
    if ep.attack_succeeded_undefended is not None:
        before = "succeeded" if ep.attack_succeeded_undefended else "failed"
        after = "succeeded" if ep.attack_succeeded_defended else "prevented"
        rows.append(("attack", f"undefended: {before}  {gl.arrow}  defended: {after}"))
    # Counted from the actions rather than from the audit summary. The summary counts a
    # question and the refusal it ends in separately, which is right for the metrics and
    # reads here as though more calls happened than the agent made.
    allowed = sum(1 for a in ep.actions if a.verdict == "ALLOW")
    refused = sum(1 for a in ep.actions if a.verdict != "ALLOW")
    asked = sum(1 for a in ep.actions if a.asked)
    rows.append(
        (
            "verdicts",
            f"{len(ep.actions)} proposed action(s): {allowed} allowed, {refused} refused"
            + (f"; {asked} put to the user first" if asked else "; nobody interrupted"),
        )
    )
    return rows


def _contested_name(scenario: Scenario) -> str:
    pattern = getattr(scenario, "contested_effect", None)
    if pattern is None:
        return "none"
    verb = getattr(pattern.verb, "value", pattern.verb)
    klass = getattr(pattern.resource_class, "value", pattern.resource_class)
    return f"{verb} {klass}"


