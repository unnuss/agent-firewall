def available() -> list[tuple[str, str, int, str]]:
    """(scenario_id, variant_id, seed, utterance) for every committed episode."""
    rows = [(r.scenario_id, r.variant_id, r.seed, r.utterance) for r in load_episodes()]
    return sorted(set(rows))


def resolve_scenes(scenario: str | None, variant: str | None, seed: int | None) -> list[Scene]:
    """Either the curated four, or one episode the caller named."""
    if scenario is None:
        return list(SCENES)
    matches = [row for row in available() if row[0] == scenario]
    if not matches:
        near = sorted({row[0] for row in available() if scenario in row[0]})[:8]
        hint = ("\nDid you mean:\n  " + "\n  ".join(near)) if near else ""
        raise SystemExit(f"no committed episode for scenario {scenario!r}{hint}")
    if variant is not None:
        matches = [row for row in matches if row[1] == variant]
        if not matches:
            raise SystemExit(f"scenario {scenario!r} has no variant {variant!r}")
    chosen_seed = seed if seed is not None else min(row[2] for row in matches)
    matches = [row for row in matches if row[2] == chosen_seed]
    if not matches:
        raise SystemExit(f"scenario {scenario!r} has no episode at seed {chosen_seed}")
    row = sorted(matches)[0]
    return [
        Scene(
            scenario_id=row[0],
            variant_id=row[1],
            seed=row[2],
            title="Replayed on request",
            selected_because="named on the command line, not curated",
            show_ask_text=True,
        )
    ]


def render(
    scope_label: str = DEFAULT_SCOPE,
    *,
    scenario: str | None = None,
    variant: str | None = None,
    seed: int | None = None,
    color: bool = False,
    glyphs: Glyphs | None = None,
    ask_text_mode: str = "flagged",
) -> str:
    """Build the whole demo as one string. Returns rather than prints, so it is testable."""
    load_all()
    ink = Ink(color)
    gl = glyphs or Glyphs.ascii()
    choice, scopes = load_scope_source(scope_label)
    gold = GoldScopes.load()
    records_list = load_episodes()
    records = {(r.scenario_id, r.variant_id, r.seed): r for r in records_list}
    scenarios = replay_mod.all_scenarios()
    scenes = resolve_scenes(scenario, variant, seed)

    lines = header(choice, len(scenes), ink, gl)
    for i, scene in enumerate(scenes, start=1):
        result = run_scene(scene, records, scenarios, scopes, gold)
        lines += render_scene(result, i, len(scenes), ink, gl, ask_text_mode)
    lines += footer(choice, len(scenes), len(records_list), ink, gl)
    return gl.sanitize(chr(10).join(lines))
