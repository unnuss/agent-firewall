"""The canonical results tables, generated from committed artifacts.

**Why this exists.** `CLAUDE.md` requires that every table in the README be regenerable by one
command. Until Phase 6.9 that was an intention: the numbers lived as prose in `README.md`,
`PROJECT_STATE.md` and a 4,700-line `EXPERIMENTS.md`, transcribed by hand, with no single place
that said which figures were final. A retracted headline (E-00i's 81.8%) was still loose in the
repository. This module makes the numbers a *function of the committed result files*, so the
front door cannot drift from the evidence and a reviewer can verify any figure by rerunning one
command.

**What it reads, and nothing else.** Committed `report.json` files under `experiments/`. It
fits no model, calls no API, re-runs no experiment, and **computes no rate of its own** — every
value is lifted from a file that `agentfw run`, `agentfw replay`, `agentfw compile-scopes` or
`agentfw learn` wrote. A number that is absent from the artifacts is rendered `(pending)` and
never estimated, which is `CLAUDE.md`'s rule expressed as code.

**The apparatus boundary is carried, not smoothed.** E-00, E-00b, E-00f, E-00h, E-01a and E-01b
are **pre-repair**: they were measured before Phase 3.5 fixed a tool contract that silently
killed a fifth of the episodes. Everything from E-00g onward is post-repair. The generated
tables label each row, because the one thing nobody may do with these figures is difference
across that line.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent.parent
EXPERIMENTS = ROOT / "experiments"

# Markers delimiting the generated region of a document. Everything between them is replaced;
# everything outside is hand-written prose and is never touched.
BEGIN = "<!-- BEGIN GENERATED by `agentfw results` -- do not edit by hand -->"
END = "<!-- END GENERATED -->"

PENDING = "(pending)"


def _load(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def _pct(value: Any, places: int = 1) -> str:
    """A rate as a percentage, or `(pending)`. Never a guess."""
    if value is None:
        return PENDING
    try:
        return f"{float(value) * 100:.{places}f}%"
    except (TypeError, ValueError):
        return PENDING


def _ci(block: Any) -> str:
    if not isinstance(block, dict):
        return ""
    ci = block.get("ci95")
    if not (isinstance(ci, list) and len(ci) == 2):
        return ""
    return f" [{float(ci[0]) * 100:.1f}, {float(ci[1]) * 100:.1f}]"


def _val(block: Any) -> Any:
    return block.get("value") if isinstance(block, dict) else None


