def load_scope_source(label: str) -> tuple[ScopeChoice, ScopeSource]:
    try:
        choice = SCOPE_BY_LABEL[label]
    except KeyError:
        known = ", ".join(SCOPE_BY_LABEL)
        raise SystemExit(f"unknown scope source {label!r}; choose one of: {known}") from None
    if choice.kind == "gold" or choice.path is None:
        return choice, GoldScopes.load()
    if not choice.path.exists():
        raise SystemExit(
            f"missing committed artifact for scope {label!r}: {choice.path}\n"
            f"This file is committed; a clean clone has it."
        )
    return choice, CompiledScopeStore.load(choice.path, label=choice.label)


def load_episodes() -> list[EpisodeResult]:
    if not EPISODES.exists():
        raise SystemExit(
            f"missing committed episodes: {EPISODES}\nThis file is committed; a clean "
            f"clone has it."
        )
    return replay_mod.load_source(EPISODES)


@dataclass
class SceneResult:
    scene: Scene
    record: EpisodeResult
    scenario: Scenario
    episode: ReplayedEpisode
    grants: tuple[str, ...]
    open_questions: tuple[str, ...]
    constraints: tuple[str, ...] = ()


def run_scene(
    scene: Scene,
    records: dict[tuple[str, str, int], EpisodeResult],
    scenarios: dict[str, Scenario],
    scopes: ScopeSource,
    gold: GoldScopes,
) -> SceneResult:
    key = (scene.scenario_id, scene.variant_id, scene.seed)
    try:
        record = records[key]
    except KeyError:
        raise SystemExit(
            f"no committed episode for {scene.scenario_id}::{scene.variant_id} "
            f"seed {scene.seed} in {EPISODES.name}"
        ) from None
    scenario = scenarios[record.scenario_id]
    scope = scopes.scope_for(record.scenario_id, record.variant_id, record.utterance)
    cfg = ReplayConfig(**POLICY)
    episode = replay_mod.replay_episode(record, scenario, scopes, cfg, gold=gold)
    return SceneResult(
        scene=scene,
        record=record,
        scenario=scenario,
        episode=episode,
        grants=tuple(sorted(str(g.effect_class) for g in scope.grants)),
        open_questions=tuple(scope.open_questions),
        # A compiled scope routinely carries the same bound once per grant it applies to.
        # Three identical lines say nothing three times, so the display collapses them; the
        # scope itself is untouched and the monitor still sees every one.
        constraints=tuple(dict.fromkeys(_render_constraint(c) for c in scope.constraints)),
    )


def _render_constraint(constraint: Any) -> str:
    parts = [str(constraint.kind)]
    for attr in ("allowed_recipients", "allowed_domains", "globs", "max_amount_usd"):
        value = getattr(constraint, attr, None)
        if value:
            parts.append(f"{attr}={value}")
    for attr in ("window_start", "window_end"):
        value = getattr(constraint, attr, None)
        if value is not None:
            parts.append(f"{attr}={value}")
    origin = "stated by the user" if getattr(constraint, "user_stated", False) else "inferred"
    return f"{' '.join(parts)}  [{origin}]"


