class Ink:
    """ANSI, or nothing at all. Honours NO_COLOR and a non-tty stdout."""

    CODES = {
        "dim": "2",
        "bold": "1",
        "red": "31",
        "green": "32",
        "yellow": "33",
        "magenta": "35",
        "cyan": "36",
    }

    def __init__(self, enabled: bool) -> None:
        self.enabled = enabled

    @classmethod
    def detect(cls, *, force_off: bool = False) -> Ink:
        if force_off or os.environ.get("NO_COLOR"):
            return cls(False)
        return cls(bool(getattr(sys.stdout, "isatty", lambda: False)()))

    def __call__(self, text: str, *styles: str) -> str:
        if not self.enabled or not styles:
            return text
        codes = ";".join(self.CODES[s] for s in styles if s in self.CODES)
        return f"\033[{codes}m{text}\033[0m" if codes else text


VERDICT_STYLE = {"ALLOW": ("green",), "ASK": ("yellow",), "BLOCK": ("red",)}

# Typography, not drawing: applied only when the attached stream cannot take the real thing.
ASCII_FALLBACK = str.maketrans(
    {
        "\u2014": "--",
        "\u2013": "-",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2026": "...",
        "\u00b7": "*",
        "\u00a0": " ",
        "\u2192": "->",
        "\u2500": "-",
        "\u2502": "|",
    }
)


@dataclass(frozen=True)
class Glyphs:
    """Box drawing, or the ASCII that survives a cp1252 console.

    Windows' legacy console encoding cannot encode U+2500, and a demo whose first act on a
    fresh clone is a UnicodeEncodeError is worse than a demo drawn in dashes. The fancy set
    is used only when the attached stream says it can encode it.
    """

    rule: str
    arrow: str
    dot: str
    bar: str

    @classmethod
    def fancy(cls) -> Glyphs:
        return cls(rule="─", arrow="→", dot="·", bar="│")

    @classmethod
    def ascii(cls) -> Glyphs:
        return cls(rule="-", arrow="->", dot="*", bar="|")

    @classmethod
    def detect(cls, stream: Any = None) -> Glyphs:
        stream = stream if stream is not None else sys.stdout
        encoding = getattr(stream, "encoding", None) or "ascii"
        probe = cls.fancy()
        try:
            "".join((probe.rule, probe.arrow, probe.dot, probe.bar)).encode(encoding)
        except (UnicodeEncodeError, LookupError):
            return cls.ascii()
        return probe

    @property
    def is_ascii(self) -> bool:
        return self.rule == "-"

    def sanitize(self, text: str) -> str:
        """Flatten the typography that is not part of the glyph set.

        Prose here and in the committed scenarios uses en/em dashes and curly quotes. They
        are not drawing characters, so they are not in ``Glyphs``, but on an ASCII stream
        they would still fail to encode. Transliterating beats the question marks that
        ``errors="replace"`` would leave behind.
        """
        return text.translate(ASCII_FALLBACK) if self.is_ascii else text


