def headline() -> list[str]:
    """The two numbers the project leads with, and their provenance."""
    undef = _load(EXPERIMENTS / "e00j_heldout_baseline" / "results" / "report.json")
    best = _load(_e14_verdict_path("perclass-sonnet-s1"))
    gold = _load(_e14_verdict_path("gold"))

    or_undef = None
    asr_undef = None
    if undef:
        spec = (undef.get("overall") or {}).get("by_specificity") or {}
        or_undef = _val((spec.get("underspecified") or {}).get("episode_rate"))
        asr_undef = _val((undef.get("overall") or {}).get("asr"))

    def contested(report: dict[str, Any] | None) -> Any:
        if not report:
            return None
        block = (report.get("contested") or {}).get("underspecified_low") or {}
        return _val(block.get("defended"))

    def asr(report: dict[str, Any] | None) -> Any:
        if not report:
            return None
        return _val((report.get("injection") or {}).get("asr_defended"))

    return [
        "| | undefended agent | best compiled scope | hand-written scope |",
        "|---|---|---|---|",
        f"| **Unlicensed consequential action executed** | **{_pct(or_undef)}** | "
        f"**{_pct(contested(best))}** | {_pct(contested(gold))} |",
        f"| **Prompt-injection attack succeeded** | **{_pct(asr_undef)}** | "
        f"**{_pct(asr(best))}** | {_pct(asr(gold))} |",
        "",
        "*60 held-out scenario triples, 621 committed episodes, same denominator across the "
        "row. Undefended from E-00j; defended from E-14's replay of those episodes.*",
    ]


def undefended_baselines() -> list[str]:
    rows = [
        "| run | underspecified overreach | explicit-low | high-authority compliance | "
        "benign BTC | ASR | apparatus |",
        "|---|---|---|---|---|---|---|",
    ]
    for source in UNDEFENDED:
        report = _load(source.path)
        overall = (report or {}).get("overall") or {}
        spec = overall.get("by_specificity") or {}
        under = _val((spec.get("underspecified") or {}).get("episode_rate"))
        under_block = (spec.get("underspecified") or {}).get("episode_rate")
        explicit = _val((spec.get("explicit") or {}).get("episode_rate"))
        rows.append(
            f"| {source.label} | {_pct(under)}{_ci(under_block)} | {_pct(explicit)} | "
            f"{_pct(_val(overall.get('compliance_rate_high')))} | "
            f"{_pct(_val(overall.get('btc_benign')))} | "
            f"{_pct(_val(overall.get('asr')))} | {source.note} |"
        )
    return rows


def verdict_table(
    arms: tuple[tuple[str, str], ...], path_for, title_note: str = ""
) -> list[str]:
    rows = [
        "| scope source | contested effect **executed** | high-authority task **completed** | "
        "asks / episode (high) | asks / episode (benign) | ASR |",
        "|---|---|---|---|---|---|",
    ]
    for stem, label in arms:
        report = _load(path_for(stem))
        if not report:
            blanks = " | ".join([PENDING] * 5)
            rows.append(f"| {label} | {blanks} |")
            continue
        contested = report.get("contested") or {}
        interrupts = report.get("interruptions") or {}
        rows.append(
            f"| {label} | "
            f"{_pct(_val((contested.get('underspecified_low') or {}).get('defended')))} | "
            f"{_pct(_val((contested.get('high_authority') or {}).get('defended')))} | "
            f"{(interrupts.get('high_authority') or {}).get('asks_per_episode', PENDING)} | "
            f"{(interrupts.get('benign') or {}).get('asks_per_episode', PENDING)} | "
            f"{_pct(_val((report.get('injection') or {}).get('asr_defended')))} |"
        )
    if title_note:
        rows += ["", f"*{title_note}*"]
    return rows


def scope_table() -> list[str]:
    rows = [
        "| compiled scope | leakage (underspecified) | retention (high) | "
        "**contrast fidelity** |",
        "|---|---|---|---|",
    ]
    for stem, label in E14_SCOPE:
        report = _load(EXPERIMENTS / "e14_validation" / "results" / stem / "report.json")
        contested = (report or {}).get("contested") or {}
        rows.append(
            f"| {label} | "
            f"{_pct(_val(contested.get('leakage_underspecified_low')))} | "
            f"{_pct(_val(contested.get('retention_high')))} | "
            f"**{_pct(_val(contested.get('contrast_fidelity')))}** |"
        )
    return rows


def learned_rungs() -> list[str]:
    """E-15's ladder, contrast fidelity across the four splits."""
    main = _load(EXPERIMENTS / "e15_learned_compiler" / "results" / "results.json")
    s4 = _load(EXPERIMENTS / "e15_learned_compiler" / "results_s4_diagnostic" / "results.json")
    pooled: dict[tuple[str, str], Any] = {}
    for source in (main, s4):
        for row in (source or {}).get("pooled") or []:
            pooled[(row["rung"], row["scheme"])] = row.get("contrast_fidelity")

    order = ("R0-prior", "R1-tfidf", "R2-frozen", "R3-finetuned")
    rows = [
        "| rung | S1 `dev`→held-out | S2 leave-one-**world**-out | "
        "S4 leave-one-**phrase**-out | S3 leave-one-**template**-out |",
        "|---|---|---|---|---|",
    ]
    for rung in order:
        cells = [_pct(pooled.get((rung, s))) for s in ("S1", "S2", "S4", "S3")]
        rows.append(f"| {rung} | " + " | ".join(cells) + " |")
    rows += [
        "",
        "*Contrast fidelity — the metric that punishes over- and under-granting at once. "
        "S2 is the split D-038 asked for and is the one that overstates generalisation "
        "(F-36); S4 is a post-hoc diagnostic and is labelled as one.*",
    ]
    return rows


def calibration() -> list[str]:
    """E-15c: the blind and calibrated R3, at both levels."""
    cal = _load(EXPERIMENTS / "e15_learned_compiler" / "results_calibration" / "result.json")
    if not cal:
        return ["", f"E-15c: {PENDING}", ""]
    held = cal.get("heldout") or {}
    config = cal.get("calibration") or {}
    blind = _load(_e15_verdict_path("armL-R3-blind"))
    calibrated = _load(_e15_verdict_path("armL-R3-calibrated"))

    def executed(report: dict[str, Any] | None) -> str:
        if not report:
            return PENDING
        block = (report.get("contested") or {}).get("underspecified_low") or {}
        return _pct(_val(block.get("defended")))

    return [
        "| | scope: leakage | scope: retention | scope: **contrast** | verdict: **executed** |",
        "|---|---|---|---|---|",
        f"| R3 blind (E-15) | 51.7% | 78.8% | **25.8%** | {executed(blind)} |",
        f"| R3 CV-calibrated (E-15c) | {_pct(held.get('leakage_underspecified'))} | "
        f"{_pct(held.get('retention_high'))} | "
        f"**{_pct(held.get('contrast_fidelity'))}** | {executed(calibrated)} |",
        "",
        f"*The cross-validated search selected `pos_weight` cap "
        f"**{config.get('pos_weight_cap', PENDING)}** — E-15's blind value — so the weighting "
        f"was never misconfigured. Out-of-fold contrast predicted "
        f"{_pct(config.get('oof_contrast'))} against "
        f"{_pct(held.get('contrast_fidelity'))} held out (F-43).*",
    ]


def render() -> str:
    """The whole generated region, in the order a reader should meet it."""
    parts: list[list[str]] = [
        ["## 1. What the architecture buys", ""],
        headline(),
        ["", "## 2. Every scope source at the verdict level", ""],
        verdict_table(
            E14_VERDICT,
            _e14_verdict_path,
            "E-14, `M0-consequential`, E-00j's 621 episodes. `tool-ceiling` is the ablation "
            "that reproduces undefended overreach (F-11): restricting the toolset is not the "
            "same intervention as compiling a scope.",
        ),
        ["", "## 3. The same arms at the scope level", ""],
        scope_table(),
        [
            "",
            "*Never read a scope row without its verdict row. The two disagree, and which way "
            "they disagree is F-38.*",
            "",
            "## 4. The learned intent compiler (Phase 6)",
            "",
        ],
        learned_rungs(),
        ["", "### The learned arms at the verdict level", ""],
        verdict_table(
            E15_VERDICT,
            _e15_verdict_path,
            "E-15, same 621 episodes and the same policy as E-14, so these rows sit in the "
            "same table as the prompted ones rather than beside them.",
        ),
        ["", "### E-15c: does calibration rescue the fine-tuned encoder?", ""],
        calibration(),
        ["", "## 5. Undefended baselines, never differenced across the apparatus boundary", ""],
        undefended_baselines(),
        [
            "",
            "*E-00i is **superseded** by E-00j and must not be quoted: measured on 11 triples "
            "with a ±23 pp interval, its 81.8% came in at 49.4% on 60. The Anthropic row is "
            "pre-repair and was not re-run — a declared budget decision. No claim in this "
            "project rests on a difference between a pre- and a post-repair number.*",
        ],
    ]
    lines: list[str] = []
    for part in parts:
        lines += part
    return "\n".join(lines).rstrip() + "\n"


def inject(document: Path) -> tuple[bool, str]:
    """Replace the generated region of `document`. Returns (changed, message)."""
    if not document.exists():
        return False, f"{document} does not exist"
    text = document.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return False, (
            f"{document} has no generated region; add the marker pair:\n  {BEGIN}\n  {END}"
        )
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    rebuilt = f"{head}{BEGIN}\n\n{render()}\n{END}{tail}"
    if rebuilt == text:
        return False, f"{document} already up to date"
    document.write_text(rebuilt, encoding="utf-8")
    return True, f"regenerated the tables in {document}"


def missing() -> list[str]:
    """Artifacts a table wanted and did not find. Empty is the healthy answer."""
    wanted: list[Path] = [s.path for s in UNDEFENDED]
    wanted += [_e14_verdict_path(s) for s, _ in E14_VERDICT]
    wanted += [
        EXPERIMENTS / "e14_validation" / "results" / s / "report.json" for s, _ in E14_SCOPE
    ]
    wanted += [_e15_verdict_path(s) for s, _ in E15_VERDICT]
    wanted += [
        EXPERIMENTS / "e15_learned_compiler" / "results" / "results.json",
        EXPERIMENTS / "e15_learned_compiler" / "results_s4_diagnostic" / "results.json",
        EXPERIMENTS / "e15_learned_compiler" / "results_calibration" / "result.json",
    ]
    return [str(p.relative_to(ROOT)) for p in wanted if not p.exists()]
