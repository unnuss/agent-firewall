WIDTH = 78


def _wrap(text: str, indent: str, width: int = WIDTH) -> list[str]:
    import textwrap

    # ``break_on_hyphens`` off: half the strings here are hyphenated identifiers
    # (``claude-sonnet-5``, ``per-class``, ``tool-ceiling``) and splitting one across a
    # line turns a name a reader is meant to recognise into two things.
    return textwrap.wrap(
        text, width=width - len(indent), break_on_hyphens=False, break_long_words=False
    ) or [""]


def _block(text: str, indent: str, width: int = WIDTH) -> list[str]:
    return [indent + line for line in _wrap(text, indent, width)]


def _labelled(label: str, text: str, indent: str = "    ", pad: int = 16) -> list[str]:
    """``label`` in a fixed column, ``text`` wrapped and hanging under itself."""
    gutter = indent + " " * pad
    wrapped = _wrap(text, gutter)
    head = indent + label.ljust(pad) + wrapped[0]
    return [head] + [gutter + line for line in wrapped[1:]]


def _short_args(args: dict[str, Any], limit: int = 60) -> str:
    if not args:
        return "{}"
    rendered = " ".join(json.dumps(args, sort_keys=True, default=str).split())
    return rendered if len(rendered) <= limit else rendered[: limit - 3] + "..."


