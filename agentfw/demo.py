"""``agentfw demo`` — watch the reference monitor allow, ask and refuse, with no API key.

**What this is.** A presenter over the replay harness (`eval/replay.py`), not a second
implementation of it. It takes episodes a real undefended agent recorded in E-00j, puts the
same tool calls in front of the same firewall the experiments use, and prints what came back.

**What it is not, and this matters more than what it is.** It is not an animation. Every
verdict, gate and sentence of explanation printed below is read out of the hash-chained
audit log *this run* produced (`core/audit.py`); nothing here is a stored transcript, and
there is no path by which this module can influence a decision. It imports the firewall; the
firewall does not import it. `agentfw/core/` is TCB code and knows nothing about scenario
ids, scope labels or demos, which is the invariant `tests/test_demo.py` asserts.

**On choosing the scenes, which is the honest risk here.** A demo picks its examples, and a
demo that picks the examples where the system happens to win is worth nothing. Three things
keep this one straight:

* The choice is *declared*. `SCENES` below states the selection rule for each one, and the
  footer of every run says how many of E-00j's 621 episodes were shown.
* The choice is *substitutable*. `--scenario` replays any committed episode through the same
  code, including the ones where the compiled scope leaks; `--list` prints them all.
* The choice is *adversarially available*. `--scope tool-ceiling` re-runs the same scenes
  under the allowlist-with-no-scope arm, where the payment goes through. If the architecture
  did nothing, that flag would show it doing nothing.

The aggregate is not printed here and no number in this file is a result. Rates live in
`README.md` and `docs/EXPERIMENTS.md` and are regenerated by `agentfw replay`, which is what
the footer points at.
"""

